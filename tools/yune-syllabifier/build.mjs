#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const YUNE_COMMIT = "8de49aab76a996f3aaa72a36b9d098bb76cc8f6e";
const DARTS_PATH = "crates/yune-core/src/dictionary/double_array.rs";
const DARTS_SHA256 = "ee7ad088ab23169a867c30dd0f3268329638172004c284e2453685e490616c35";
const DICTIONARY_PATH = "apps/yune-web/public/schema/jyut6ping3.dict.yaml";
const DICTIONARY_SHA256 = "b0abf4fbcbf18b8cf05f4689ea05a12be6cf301f29a7316699e2b1ab9c24d172";
const LICENSE_PATH = "LICENSE";
const LICENSE_SHA256 = "24205c80352463dc9eb95e9cf1b8efdefc153d1128977c8b7b8b95787d958a92";
const DICTIONARY_PROVENANCE_PATH = "apps/yune-web/public-demo/PROVENANCE.md";
const DICTIONARY_PROVENANCE_SHA256 = "5705803d89ce8fdfcb4a0b146119491b04c57a17ce025510e78194d2bbec07a1";
const EXPECTED_SYLLABLE_COUNT = 706;
const VERSION = "yune-darts-8de49aab/jyut6ping3-2024.11.14/contest-1";

const toolRoot = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(toolRoot, "../..");
const argument = process.argv.indexOf("--yune");
const yuneRoot = argument >= 0 ? resolve(process.argv[argument + 1]) : resolve(projectRoot, "../yune");

if (!existsSync(resolve(yuneRoot, ".git"))) {
  throw new Error(`Yune checkout not found. Pass --yune <checkout> (looked in ${yuneRoot}).`);
}

function gitFile(path) {
  return execFileSync("git", ["-C", yuneRoot, "show", `${YUNE_COMMIT}:${path}`], {
    encoding: "buffer",
    maxBuffer: 32 * 1024 * 1024,
  });
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function verifiedGitFile(path, expectedHash) {
  const bytes = gitFile(path);
  const actualHash = sha256(bytes);
  if (actualHash !== expectedHash) {
    throw new Error(`${path} SHA-256 mismatch: expected ${expectedHash}, got ${actualHash}`);
  }
  return bytes;
}

const darts = verifiedGitFile(DARTS_PATH, DARTS_SHA256);
const dictionary = verifiedGitFile(DICTIONARY_PATH, DICTIONARY_SHA256);
const license = verifiedGitFile(LICENSE_PATH, LICENSE_SHA256);
const dictionaryProvenance = verifiedGitFile(
  DICTIONARY_PROVENANCE_PATH,
  DICTIONARY_PROVENANCE_SHA256,
);

const syllables = new Set();
let inBody = false;
for (const line of dictionary.toString("utf8").split(/\r?\n/u)) {
  if (line === "...") {
    inBody = true;
    continue;
  }
  if (!inBody || line === "" || line.startsWith("#")) continue;
  const fields = line.split("\t");
  if (fields.length < 2) continue;
  for (const toned of fields[1].trim().split(/\s+/u)) {
    if (!/^[a-z]+[1-6]?$/u.test(toned)) {
      throw new Error(`Unexpected Jyutping code ${JSON.stringify(toned)} in ${DICTIONARY_PATH}`);
    }
    syllables.add(toned.replace(/[1-6]$/u, ""));
  }
}

const sortedSyllables = [...syllables].sort();
if (sortedSyllables.length !== EXPECTED_SYLLABLE_COUNT) {
  throw new Error(`Expected ${EXPECTED_SYLLABLE_COUNT} syllables, extracted ${sortedSyllables.length}`);
}

const generated = [
  "// Generated by ../build.mjs from the pinned Yune dictionary; do not edit.",
  `// Yune commit: ${YUNE_COMMIT}`,
  `// Source: ${DICTIONARY_PATH}`,
  `// Source SHA-256: ${DICTIONARY_SHA256}`,
  "pub const SYLLABLES: &[&str] = &[",
  ...sortedSyllables.map(syllable => `    ${JSON.stringify(syllable)},`),
  "];",
  "",
].join("\n");

mkdirSync(resolve(toolRoot, "src"), { recursive: true });
writeFileSync(resolve(toolRoot, "src/double_array.rs"), darts);
writeFileSync(resolve(toolRoot, "src/syllables.rs"), generated);
writeFileSync(resolve(toolRoot, "LICENSE.YUNE-CODE"), license);
writeFileSync(resolve(toolRoot, "PROVENANCE.YUNE-WEB.md"), dictionaryProvenance);

execFileSync("cargo", [
  "build",
  "--manifest-path", resolve(toolRoot, "Cargo.toml"),
  "--target", "wasm32-unknown-unknown",
  "--release",
], { stdio: "inherit" });

const wasmSource = resolve(toolRoot, "target/wasm32-unknown-unknown/release/contest_yune_syllabifier.wasm");
const wasm = readFileSync(wasmSource);
const vendorRoot = resolve(projectRoot, "demo/vendor/yune");
mkdirSync(vendorRoot, { recursive: true });
writeFileSync(resolve(vendorRoot, "syllabifier.wasm"), wasm);
writeFileSync(resolve(vendorRoot, "LICENSE.yune-code.txt"), license);
writeFileSync(resolve(vendorRoot, "PROVENANCE.yune-web.md"), dictionaryProvenance);
writeFileSync(resolve(vendorRoot, "syllabifier.provenance.json"), `${JSON.stringify({
  version: VERSION,
  yuneCommit: YUNE_COMMIT,
  darts: { path: DARTS_PATH, sha256: DARTS_SHA256 },
  dictionary: {
    path: DICTIONARY_PATH,
    sha256: DICTIONARY_SHA256,
    version: "2024.11.14",
    extraction: "all tab-separated code tokens; remove one trailing tone digit 1-6; deduplicate; no derive/fuzzy rules",
    provenance: {
      path: DICTIONARY_PROVENANCE_PATH,
      sha256: DICTIONARY_PROVENANCE_SHA256,
      attribution: "Yune records the Cantonese dictionary assets as TypeDuck-origin assets used with project-owner approval from the TypeDuck author.",
      licenseScope: "The dictionary header declares no standalone license; the Yune MIT code license is not asserted for dictionary data.",
    },
  },
  dartsCodeLicense: { path: LICENSE_PATH, sha256: LICENSE_SHA256, spdx: "MIT" },
  syllableCount: sortedSyllables.length,
  wasmSha256: sha256(wasm),
}, null, 2)}\n`);

console.log(`Built ${wasm.length} byte WASM with ${sortedSyllables.length} exact toneless syllables.`);
